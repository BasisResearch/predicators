"""Generate appendix tables from the paper figure's selected-run manifest."""

import argparse
import json
from pathlib import Path
from statistics import mean
from typing import Any, Dict, List

ARMS = {
    "oracle_dynamics": "Oracle dynamics",
    "MB": "EMPIRIC",
    "MF": "Direct agent",
    "mf_scene_package": "Direct + scene",
    "standalone": "Standalone sim.",
    "no_fitting": "No harness fitting",
    "no_uncertainty": "No explicit uncert.",
}
DOMAIN_ORDER = ["Domino", "Bridge", "Balloons", "Boil", "Fan"]
HEADER = ("% Generated by scripts/plotting/export_paper_results_tables.py; "
          "do not edit.")


def export_tables(manifest: Path, output_dir: Path) -> None:
    """Use exactly the selected records, without filling missing results."""
    records: List[Dict[str, Any]] = json.loads(manifest.read_text())["records"]
    grouped: Dict[str, Dict[str, Dict[int, Dict[str, Any]]]] = {
        domain: {arm: {}
                 for arm in ARMS}
        for domain in DOMAIN_ORDER
    }
    domain_sources: Dict[str, str] = {}
    for record in records:
        domain = record["domain"].split(" (", 1)[0]
        arm = record["arm"]
        seed = record["seed"]
        if domain not in grouped or arm not in ARMS or seed not in range(5):
            raise ValueError(f"Unexpected paper record: {record}")
        if domain_sources.setdefault(domain,
                                     record["domain"]) != record["domain"]:
            raise ValueError(f"Mixed domain variants for {domain}")
        if seed in grouped[domain][arm]:
            raise ValueError(f"Duplicate record: {domain}, {arm}, seed {seed}")
        grouped[domain][arm][seed] = record

    seeds = [
        HEADER, r"\begin{tabular}{@{}lrrrrr@{}}", r"\toprule",
        r"Agent & Seed 0 & Seed 1 & Seed 2 & Seed 3 & Seed 4 \\", r"\midrule"
    ]
    for index, domain in enumerate(DOMAIN_ORDER):
        if index:
            seeds.append(r"\addlinespace[3pt]")
        seeds.append(r"\multicolumn{6}{l}{\textbf{" + domain + r"}} \\")
        for arm, label in ARMS.items():
            cells = []
            for seed in range(5):
                seed_record = grouped[domain][arm].get(seed)
                if seed_record is None:
                    cells.append("--")
                else:
                    cells.append(
                        f"{seed_record['won']}/{seed_record['levels']}; "
                        f"{seed_record['steps']:,}; {seed_record['resets']}")
            seeds.append(label + " & " + " & ".join(cells) + r" \\")
    seeds.extend([r"\bottomrule", r"\end{tabular}"])

    costs = [
        HEADER, r"\begin{tabular}{@{}lrrrrr@{}}", r"\toprule",
        "Agent & " + " & ".join(DOMAIN_ORDER) + r" \\", r"\midrule"
    ]
    for arm, label in ARMS.items():
        cells = []
        for domain in DOMAIN_ORDER:
            steps = [
                r["steps"] for r in grouped[domain][arm].values()
                if r["won"] == r["levels"]
            ]
            cells.append(
                f"{mean(steps):,.1f} ({len(steps)})" if steps else "--")
        costs.append(label + " & " + " & ".join(cells) + r" \\")
    costs.extend([r"\bottomrule", r"\end{tabular}"])
    output_dir.mkdir(parents=True, exist_ok=True)
    (output_dir / "seed_table.tex").write_text("\n".join(seeds) + "\n")
    (output_dir / "successful_steps.tex").write_text("\n".join(costs) + "\n")


def main() -> None:
    """Parse paths for a selected figure manifest and the paper table
    folder."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("manifest", type=Path)
    parser.add_argument("output_dir", type=Path)
    args = parser.parse_args()
    export_tables(args.manifest, args.output_dir)


if __name__ == "__main__":
    main()
