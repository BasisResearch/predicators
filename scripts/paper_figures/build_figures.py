class Drawing:
    """SVG composition with raster panels and PDF/PNG export."""

    def __init__(self, height: float) -> None:
        self.height = height
        self.root = ET.Element(f"{{{NS}}}svg", {
            "width": "528",
            "height": str(height),
            "viewBox": f"0 0 528 {height}"
        })
        self.root.append(
            ET.Comment(
                " Generated by scripts/build_figures.py; do not edit. "))
        self.add("rect", x=0, y=0, width=528, height=height, fill="white")

    def add(self, tag: str, **kw: Any) -> ET.Element:
        """Append an SVG element."""
        return ET.SubElement(
            self.root, f"{{{NS}}}{tag}",
            {k.replace("_", "-"): str(v)
             for k, v in kw.items()})

    def text(self,
             x: float,
             y: float,
             text: str,
             size: float = 10.5,
             color: str = INK,
             weight: str = "normal",
             anchor: str = "start",
             mono: bool = False) -> None:
        """Place one text label."""
        e = self.add("text",
                     x=x,
                     y=y,
                     font_family="DejaVu Sans Mono" if mono else "DejaVu Sans",
                     font_size=size,
                     fill=color,
                     font_weight=weight,
                     text_anchor=anchor)
        if mono:
            e.set("{http://www.w3.org/XML/1998/namespace}space", "preserve")
        e.text = text

    def lines(self,
              x: float,
              y: float,
              lines: Sequence[str],
              size: float = 10.5,
              color: str = INK,
              leading: float = 15,
              mono: bool = False) -> None:
        """Place evenly spaced text lines."""
        for i, line in enumerate(lines):
            self.text(x, y + leading * i, line, size, color, mono=mono)

    def rect(self,
             x: float,
             y: float,
             w: float,
             h: float,
             fill: str = "#f4f7f8",
             stroke: str = "#d3dde1",
             radius: float = 5,
             dash: Optional[str] = None) -> None:
        """Draw a rounded rectangle."""
        kw: Dict[str, Any] = dict(x=x,
                                  y=y,
                                  width=w,
                                  height=h,
                                  rx=radius,
                                  fill=fill,
                                  stroke=stroke,
                                  stroke_width=.8)
        if dash:
            kw["stroke_dasharray"] = dash
        self.add("rect", **kw)

    def arrow(self,
              x1: float,
              y1: float,
              x2: float,
              y2: float,
              color: str = MUTED) -> None:
        """Draw a directed connector."""
        self.add("path",
                 d=f"M{x1} {y1} L{x2} {y2}",
                 fill="none",
                 stroke=color,
                 stroke_width=1.3)
        dx, dy = x2 - x1, y2 - y1
        length = math.hypot(dx, dy)
        ux, uy = dx / length, dy / length
        points = [(x2, y2), (x2 - 5 * ux - 2.5 * uy, y2 - 5 * uy + 2.5 * ux),
                  (x2 - 5 * ux + 2.5 * uy, y2 - 5 * uy - 2.5 * ux)]
        self.add("polygon",
                 points=" ".join(f"{x},{y}" for x, y in points),
                 fill=color)

    def photo(self,
              name: str,
              x: float,
              y: float,
              w: float,
              h: float,
              crop: Optional[Tuple[int, int, int, int]] = None,
              contain: bool = False,
              gui_key: Optional[str] = None) -> None:
        """Embed a cropped source photograph."""
        gui_manifest = ROOT / "data/gui-figure-manifest.json"
        gui_panel = None
        if gui_manifest.exists():
            gui_panel = json.loads(gui_manifest.read_text())["lookup"].get(
                gui_key or f"{self.height}:{x}:{y}")
        if gui_panel:
            sources = [ROOT / gui_panel]
            crop = None
        else:
            sources = [
                p for p in (FIG / "sources").glob(f"{name}.*")
                if p.suffix.lower() in {'.png', '.jpg', '.jpeg'}
            ]
        # Local GUI re-renders can replace pixels without changing panel IDs,
        # archived evidence, or the layout. Never silently overwrite sources.
        overrides = ROOT / "data/figure-render-overrides.json"
        if overrides.exists():
            USED_IMAGES.add(overrides)
            replacements = json.loads(overrides.read_text())
            replacement = replacements.get(gui_key) or replacements.get(name)
            if replacement:
                sources = [ROOT / replacement["path"]]
                crop = replacement.get("crop")
        assert len(sources) == 1, (name, sources)
        USED_IMAGES.add(sources[0])
        im = Image.open(sources[0]).convert("RGB")
        if crop is not None:
            im = im.crop(crop)
        size = (round(w * 4), round(h * 4))
        if contain:
            im = ImageOps.pad(im,
                              size,
                              method=Image.Resampling.LANCZOS,
                              color="#f4f7f8")
        else:
            im = ImageOps.fit(im, size, method=Image.Resampling.LANCZOS)
        stream = io.BytesIO()
        im.save(stream, format="PNG")
        self.add("image",
                 x=x,
                 y=y,
                 width=w,
                 height=h,
                 href="data:image/png;base64," +
                 base64.b64encode(stream.getvalue()).decode())

    def scene(self,
              domain: str,
              state: str,
              x: float,
              y: float,
              w: float,
              h: float,
              gui_key: Optional[str] = None) -> None:
        """Embed a domain render, including the updated Balloons assets."""
        if domain == "Balloons":
            self.photo(f"balloons_refined_{state}",
                       x,
                       y,
                       w,
                       h,
                       crop=(240, 260, 1050, 790),
                       gui_key=gui_key)
        else:
            self.photo(f"{domain.lower()}_{state}",
                       x,
                       y,
                       w,
                       h,
                       crop=CROPS[domain.lower()],
                       gui_key=gui_key)

    def save(self, name: str) -> None:
        """Write vector, PDF, and raster versions."""
        raw = ET.tostring(self.root, encoding="utf-8", xml_declaration=True)
        (OUTPUT / f"{name}.svg").write_bytes(raw)
        cairosvg.svg2pdf(bytestring=raw, write_to=str(OUTPUT / f"{name}.pdf"))
        cairosvg.svg2png(bytestring=raw,
                         write_to=str(OUTPUT / f"{name}.png"),
                         scale=2)


