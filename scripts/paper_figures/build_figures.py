def environments() -> None:
    """Figure 3 now shows recorded execution, not the domain gallery."""
    archive = ROOT / "data/trajectories/figure3.json"
    USED_IMAGES.add(archive)
    rows = json.loads(archive.read_text())["rows"]
    d = Drawing(234)
    for row_index, row in enumerate(rows):
        y = row_index * 119
        title = d.add("text",
                      x=0,
                      y=0,
                      font_family="DejaVu Sans",
                      font_size=11,
                      fill=TEAL,
                      font_weight="bold",
                      text_anchor="middle",
                      transform=f"translate(12 {y+49}) rotate(-90)")
        title.text = row["domain"]
        for i, frame in enumerate(row["frames"]):
            source = FIG / "sources" / (frame["name"] + ".png")
            assert hashlib.sha256(
                source.read_bytes()).hexdigest() == frame["sha256"]
            x = 24 + i * 103
            d.photo(frame["name"],
                    x,
                    y,
                    92,
                    98,
                    crop=row["crop"],
                    gui_key=frame["name"])
            d.text(x + 46,
                   y + 111,
                   f"{frame['label']} · t={frame['level_step']:,}",
                   7.3,
                   anchor="middle")
            if i < 4:
                d.arrow(x + 94, y + 49, x + 101, y + 49)
    d.save("fig4_environments")


def build_overview_figures() -> None:
    """Rebuild Figures 1 and 3; Figure 2 is maintained in Figma."""
    OUTPUT.mkdir(parents=True, exist_ok=True)
    USED_IMAGES.clear()
    teaser()
    environments()
    inputs = USED_IMAGES | {
        Path(__file__), ROOT / "data/gui-figure-manifest.json"
    }
    outputs = [
        OUTPUT / f"{name}.{ext}"
        for name in ("fig1_residual", "fig4_environments")
        for ext in ("pdf", "svg", "png")
    ]

    def hashes(paths: Iterable[Path], base: Path) -> Dict[str, str]:
        return {
            str(p.relative_to(base)):
            hashlib.sha256(p.read_bytes()).hexdigest()
            for p in sorted(paths)
        }

    (ROOT / "data/overview-figure-build-manifest.json").write_text(
        json.dumps(
            {
                "generated_by":
                "scripts/paper_figures/build_figures.py --overview; "
                "do not edit manually",
                "inputs":
                hashes(inputs, ROOT),
                "outputs":
                hashes(outputs, OUTPUT)
            },
            indent=2) + "\n")


if __name__ == "__main__":
    import argparse
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--overview", action="store_true", required=True)
    parser.parse_args()
    build_overview_figures()
