"""Capture MB repair comparisons using the shared scorecard checks."""
import argparse
import csv
import io
import json
from pathlib import Path

from make_crossdomain_table import ROOT, aggregate, atomic_write, capture, \
    number


def main():
    """Refresh explicitly, otherwise render the saved snapshot."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=ROOT)
    parser.add_argument(
        "--manifest",
        type=Path,
        default=ROOT /
        "logs/mb_repair_20260909/experiments/launch-manifest.json")
    parser.add_argument("--output",
                        type=Path,
                        default=ROOT / "docs/uncertainty-results")
    parser.add_argument("--refresh", action="store_true")
    parser.add_argument("--require-finished", action="store_true")
    args = parser.parse_args()
    args.output.mkdir(parents=True, exist_ok=True)
    snapshot = args.output / "model-repair-snapshot.json"
    if args.refresh:
        payload = capture(args.manifest, args.root)
        payload[
            "generated_by"] = "make_model_repair_table.py; do not edit manually"
        atomic_write(snapshot, json.dumps(payload, indent=2) + "\n")
    else:
        payload = json.loads(snapshot.read_text())
    summaries = [aggregate(row) for row in payload["rows"]]
    finished = sum(row["finished_seeds"] for row in summaries)
    total = sum(row["seeds"] for row in summaries)
    lines = [
        "# MB repair on the original noisy tasks",
        "",
        "Generated by `make_model_repair_table.py`; do not edit manually.",
        f"Captured at {payload['observed_at']}; {finished}/{total} seeds finished.",
        "All rows keep the six uncertainty flags on.",
        "The paired balloons arms differ only in the advisory repair flag.",
        "Bridge, fan, domino and boil are regression runs; their controls are historical.",
        "These development seeds have already been inspected during debugging.",
        "Mean steps includes only whole-run successful seeds; solve rate and resets use all seeds.",
        "Incomplete arms withhold their averages.",
        "",
        "| Domain | Noise | Arm | Finished | Successful | Solve rate | Mean steps (successful) | Mean resets (all) |",
        "|---|---|---|---:|---:|---:|---:|---:|",
    ]
    for row in summaries:
        complete = row["status"] == "Complete"
        solve = f"{number(row['solve_rate_pct'])}%" if complete else "Pending"
        steps = number(row["mean_steps_successful"]) if complete else "Pending"
        resets = number(row["mean_resets"]) if complete else "Pending"
        lines.append(
            f"| {row['domain']} | {row['noise']} | {row['arm']} | "
            f"{row['finished_seeds']}/{row['seeds']} | {row['successful_seeds']} | "
            f"{solve} | {steps} | {resets} |")
    lines += [
        "", f"Frozen runtime: `{payload['base_sha']}`.",
        "Source: [snapshot](model-repair-snapshot.json), [TSV](model-repair-summary.tsv).",
        "Protocol and validation: [plan](model-repair-plan.md).",
        "Simulator cost is recorded in fit/validation tool reports; the table does not estimate total simulator CPU time.",
        ""
    ]
    atomic_write(args.output / "model-repair-table.md", "\n".join(lines))
    stream = io.StringIO()
    writer = csv.DictWriter(stream,
                            fieldnames=list(summaries[0]),
                            delimiter="\t",
                            lineterminator="\n")
    writer.writeheader()
    writer.writerows(summaries)
    atomic_write(args.output / "model-repair-summary.tsv", stream.getvalue())
    print(f"Wrote model repair table: {finished}/{total} seeds finished")
    if args.require_finished and finished != total:
        raise SystemExit("Missing or unfinished repair runs")


if __name__ == "__main__":
    main()
